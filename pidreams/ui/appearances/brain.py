"""Digital brain: a 3D holographic brain of points and links that drifts slowly on its own.

The shape is generated by code with a fixed seed (always the same brain, no third-party art):
two hemispheres split by the longitudinal fissure, folds (gyri) as ridges on the surface, the
cerebellum with its fine folds at the back and the brainstem. Each point links to its nearest
neighbours. Idle, a few points twinkle; listening, the whole brain glows softly; thinking,
pulses of light run along the links; speaking, waves of light leave the centre with the voice.
Painted with numpy into one opaque image (see holo.py).
"""

import math

import numpy as np

from pidreams.ui import theme
from pidreams.ui.appearances.holo import HoloAppearance

_SEED = 314
_CEREBRUM, _CEREBELLUM, _STEM = 1500, 320, 90     # points per part
_NEIGHBORS = 3
_LINK_DOTS = 3                 # dots drawn along each link
_PULSES = 26


def _sphere(n: int, rng) -> np.ndarray:
    """n evenly spread unit directions (Fibonacci sphere), slightly jittered."""
    i = np.arange(n) + 0.5
    phi = np.arccos(1 - 2 * i / n)
    theta = math.pi * (1 + 5 ** 0.5) * i + rng.normal(0, 0.02, n)
    return np.column_stack([np.sin(phi) * np.cos(theta), np.cos(phi), np.sin(phi) * np.sin(theta)])


def _folds(p: np.ndarray, rng, ridges: int, freq: float) -> np.ndarray:
    """Ridges and grooves: |sin| of a few random plane waves, so they read as gyri and sulci."""
    total = np.zeros(len(p))
    for _ in range(ridges):
        k = rng.normal(size=3)
        k /= np.linalg.norm(k)
        total += 1 - 2 * np.abs(np.sin(freq * p @ k + rng.uniform(0, math.tau)))
    return total / ridges


def _shape(rng) -> tuple[np.ndarray, np.ndarray]:
    """(points x right, y up, z front; part of each point: 0 cerebrum, 1 cerebellum, 2 stem)."""
    u = _sphere(_CEREBRUM, rng)
    p = u * np.array([0.6, 0.5, 0.82])
    low = p[:, 1] < -0.12                                   # flatter underside
    p[low, 1] = -0.12 + (p[low, 1] + 0.12) * 0.5
    p[:, 1] -= 0.18 * np.exp(-((p[:, 2] - 0.15) / 0.25) ** 2) * (p[:, 1] < -0.05)   # temporal notch
    side = np.sign(p[:, 0])
    p[:, 0] = side * (np.abs(p[:, 0]) * 0.94 + 0.035)       # the two hemispheres, apart
    top = (np.abs(u[:, 0]) < 0.14) & (u[:, 1] > 0)
    p[top, 1] -= 0.07 * (1 - np.abs(u[top, 0]) / 0.14)      # the fissure dips between them
    p += u * (0.045 * _folds(p, rng, 5, 11.0))[:, None]

    c = _sphere(_CEREBELLUM, rng)
    c = c[c[:, 1] < 0.35] * np.array([0.42, 0.2, 0.26]) + np.array([0, -0.33, -0.55])
    c[:, 1] += 0.012 * np.sin(c[:, 1] * 95)                  # its fine horizontal folds

    a = rng.uniform(0, math.tau, _STEM)
    h = rng.uniform(0, 1, _STEM)
    stem = np.column_stack([0.085 * np.cos(a), -0.3 - 0.5 * h, -0.28 - 0.08 * h + 0.085 * np.sin(a)])
    points = np.vstack([p, c, stem]).astype(np.float32)
    part = np.concatenate([np.zeros(len(p)), np.ones(len(c)), np.full(_STEM, 2)]).astype(np.int8)
    points -= (points.max(0) + points.min(0)) / 2
    points /= np.ptp(points[:, 1]) * 1.05
    return points, part


def _links(points: np.ndarray, part: np.ndarray) -> np.ndarray:
    """Each point to its nearest neighbours of the same part; pairs only once."""
    d = ((points[:, None, :] - points[None, :, :]) ** 2).sum(-1)
    d[part[:, None] != part[None, :]] = np.inf
    np.fill_diagonal(d, np.inf)
    near = np.argsort(d, axis=1)[:, :_NEIGHBORS]
    pairs = {(min(i, int(j)), max(i, int(j))) for i in range(len(points)) for j in near[i]}
    return np.array(sorted(pairs), dtype=np.int32)


class BrainCanvas(HoloAppearance):
    MAX_SIZE = 560      # measured with tests/eval/appearance_cost.py (2026-11-03)
    YAW_OFFSET, PITCH_OFFSET = -0.95, 0.12        # rests in three-quarter view, a little from above

    def __init__(self, parent, size: int = 300, bg: str = theme.GLASS, on_fail=None):
        super().__init__(parent, size, bg, on_fail)
        rng = np.random.default_rng(_SEED)
        self._points, part = _shape(rng)
        self._edges = _links(self._points, part)
        self._dot_edge = np.repeat(np.arange(len(self._edges)), _LINK_DOTS)
        self._dot_t = np.tile((np.arange(_LINK_DOTS) + 1) / (_LINK_DOTS + 1), len(self._edges)).astype(np.float32)
        self._phase = rng.uniform(0, math.tau, len(self._points)).astype(np.float32)
        self._radius = np.linalg.norm(self._points, axis=1)
        self._neighbors = [[] for _ in self._points]
        for i, j in self._edges:
            self._neighbors[i].append(j)
            self._neighbors[j].append(i)
        self._rng = np.random.default_rng(_SEED + 1)
        self._pulses = []          # [from, to, progress]

    def _wander(self) -> None:
        """Slow drift that never quite repeats: sines with unrelated periods (no cursor following)."""
        t = self._t
        self._yaw = 0.45 * math.sin(t * 0.21) + 0.15 * math.sin(t * 0.57 + 1.3)
        self._pitch = 0.12 * math.sin(t * 0.17 + 0.6) + 0.05 * math.sin(t * 0.43)

    # ── activity ──

    def _lights(self) -> np.ndarray:
        """Brightness of each point (0..1) for the current state."""
        t = self._t
        if self.state == "speaking":
            front = (t * 1.4) % 1.0 * self._radius.max()           # a wave leaving the centre
            wave = np.exp(-((self._radius - front) / 0.06) ** 2)
            return 0.25 + (0.35 + 0.65 * self.voice) * wave + 0.25 * self.voice
        if self.state == "listening":
            return 0.45 + 0.12 * np.sin(t * 2.0 + self._phase)
        if self.state == "thinking":
            return np.full(len(self._points), 0.3, np.float32)
        return np.where(np.sin(t * 0.9 + self._phase * 3) > 0.93, 1.0, 0.3)

    def _advance_pulses(self) -> None:
        if self.state != "thinking":
            self._pulses.clear()
            return
        while len(self._pulses) < _PULSES:
            i = int(self._rng.integers(len(self._points)))
            if self._neighbors[i]:
                self._pulses.append([i, int(self._rng.choice(self._neighbors[i])), 0.0, 6])
        alive = []
        for pulse in self._pulses:
            pulse[2] += 0.22
            if pulse[2] >= 1:
                pulse[3] -= 1
                if pulse[3] == 0:
                    continue
                previous, pulse[0] = pulse[0], pulse[1]
                options = [j for j in self._neighbors[pulse[0]] if j != previous] or [previous]
                pulse[1], pulse[2] = int(self._rng.choice(options)), 0.0
            alive.append(pulse)
        self._pulses = alive

    # ── drawing ──

    def _frame_holder(self):
        s = self.size
        self._wander()
        self._advance_pulses()
        v = self._points @ self._rotation().T
        scale = s * 0.74
        sx, sy = s / 2 + v[:, 0] * scale, s / 2 - v[:, 1] * scale
        depth = (v[:, 2] - v[:, 2].min()) / max(float(np.ptp(v[:, 2])), 1e-6)
        base, accent = self._state_colors()
        light = self._lights()
        img = self._new_frame()

        e = self._edges[self._dot_edge]
        t = self._dot_t
        lx = sx[e[:, 0]] + (sx[e[:, 1]] - sx[e[:, 0]]) * t
        ly = sy[e[:, 0]] + (sy[e[:, 1]] - sy[e[:, 0]]) * t
        ld = depth[e[:, 0]] + (depth[e[:, 1]] - depth[e[:, 0]]) * t
        ll = (light[e[:, 0]] + light[e[:, 1]]) / 2
        self._plot(img, lx, ly, base, (0.1 + 0.25 * ld) * (0.5 + 0.6 * ll))
        self._plot(img, sx, sy, base, (0.3 + 0.45 * depth) * light, halo=True)
        bright = light > 0.8
        if bright.any():
            self._plot(img, sx[bright], sy[bright], accent, light[bright] * (0.6 + 0.4 * depth[bright]), halo=True)
        if self._pulses:
            p = np.array(self._pulses, dtype=np.float32)
            a, b, k = p[:, 0].astype(int), p[:, 1].astype(int), p[:, 2]
            for frac in (0.0, -0.08, -0.16):                   # a short glowing tail
                kk = np.clip(k + frac, 0, 1)
                self._plot(img, sx[a] + (sx[b] - sx[a]) * kk, sy[a] + (sy[b] - sy[a]) * kk, accent,
                           np.full(len(p), 1.2 + frac * 4), halo=True)
        self._show(img)
